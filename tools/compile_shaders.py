#!/usr/bin/env python3
"""Compile engine shaders to SPIR-V and embed them as C++ arrays.

The generated header is committed so the engine builds without a shader
compiler. Run this after editing any file in engine/render/shaders/.

  python3 tools/compile_shaders.py           # regenerate
  python3 tools/compile_shaders.py --check   # fail if the header is stale (CI)

Requires glslangValidator (Khronos glslang, BSD-3-Clause and others).
"""
import pathlib
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHADER_DIR = ROOT / "engine" / "render" / "shaders"
OUTPUT = ROOT / "engine" / "render" / "src" / "generated" / "shaders.inl"
SHADERS = [
    ("mesh.vert", "kMeshVertSpv"),
    ("mesh.frag", "kMeshFragSpv"),
    ("grid.vert", "kGridVertSpv"),
    ("grid.frag", "kGridFragSpv"),
]


def compile_one(source: pathlib.Path, workdir: pathlib.Path) -> bytes:
    out = workdir / (source.name + ".spv")
    subprocess.run(
        ["glslangValidator", "--target-env", "vulkan1.3", "-V", "-o", str(out), str(source)],
        check=True, capture_output=True, text=True)
    return out.read_bytes()


def render_header(blobs) -> str:
    lines = [
        "// Generated by tools/compile_shaders.py from engine/render/shaders. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace aether::render::shaders {",
        "",
    ]
    for (name, symbol), blob in zip(SHADERS, blobs):
        words = [int.from_bytes(blob[i:i + 4], "little") for i in range(0, len(blob), 4)]
        lines.append(f"// {name}")
        lines.append(f"inline constexpr std::uint32_t {symbol}[] = {{")
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace aether::render::shaders")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    if shutil.which("glslangValidator") is None:
        sys.exit("glslangValidator not found (install glslang-tools)")
    with tempfile.TemporaryDirectory() as tmp:
        blobs = [compile_one(SHADER_DIR / name, pathlib.Path(tmp)) for name, _ in SHADERS]
    header = render_header(blobs)
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != header:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run tools/compile_shaders.py")
            return 1
        print("shaders up to date")
        return 0
    OUTPUT.write_text(header)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
