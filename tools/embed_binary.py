#!/usr/bin/env python3
"""Embed a binary file as a C++ byte array header.

  python3 tools/embed_binary.py <input> <output.inl> <symbol>

Used for the editor UI font so the editor is a single self-contained exe.
"""
import pathlib
import sys


def main() -> int:
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    src, dst, symbol = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3]
    data = src.read_bytes()
    lines = [
        f"// Generated by tools/embed_binary.py from {src.as_posix()}. Do not edit.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        f"inline constexpr unsigned char {symbol}[] = {{",
    ]
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
    lines.append("};")
    lines.append(f"inline constexpr std::size_t {symbol}_size = sizeof({symbol});")
    lines.append("")
    dst.write_text("\n".join(lines))
    print(f"wrote {dst} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
